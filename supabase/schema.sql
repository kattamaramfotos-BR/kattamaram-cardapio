create extension if not exists pgcrypto;

-- ---------- TABELAS ----------
create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category_id uuid references public.categories(id) on delete set null,
  unit text not null default 'UN',
  minimum_stock numeric(14,3) not null default 0 check (minimum_stock >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.locations (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  type text not null check (type in ('container','boat','other')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.inventory (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete cascade,
  location_id uuid not null references public.locations(id) on delete cascade,
  quantity numeric(14,3) not null default 0 check (quantity >= 0),
  updated_at timestamptz not null default now(),
  unique(product_id, location_id)
);

create table if not exists public.stock_entries (
  id bigint generated by default as identity primary key,
  entry_date date not null default current_date,
  invoice_number text,
  invoice_file text,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.stock_entry_items (
  id bigint generated by default as identity primary key,
  entry_id bigint not null references public.stock_entries(id) on delete cascade,
  product_id uuid not null references public.products(id),
  quantity numeric(14,3) not null check (quantity > 0),
  unit text not null default 'UN',
  created_at timestamptz not null default now()
);

create table if not exists public.transfers (
  id bigint generated by default as identity primary key,
  from_location_id uuid not null references public.locations(id),
  to_location_id uuid not null references public.locations(id),
  transfer_date timestamptz not null default now(),
  notes text,
  created_at timestamptz not null default now(),
  check (from_location_id <> to_location_id)
);

create table if not exists public.transfer_items (
  id bigint generated by default as identity primary key,
  transfer_id bigint not null references public.transfers(id) on delete cascade,
  product_id uuid not null references public.products(id),
  quantity numeric(14,3) not null check (quantity > 0),
  unit text not null default 'UN'
);

create table if not exists public.stock_movements (
  id bigint generated by default as identity primary key,
  product_id uuid not null references public.products(id),
  location_id uuid not null references public.locations(id),
  movement_type text not null check (
    movement_type in ('ENTRY','TRANSFER_OUT','TRANSFER_IN','ADJUSTMENT','CONSUMPTION','LOSS')
  ),
  quantity numeric(14,3) not null,
  reference_type text,
  reference_id text,
  notes text,
  created_at timestamptz not null default now()
);

create index if not exists idx_inventory_product on public.inventory(product_id);
create index if not exists idx_inventory_location on public.inventory(location_id);
create index if not exists idx_movements_product on public.stock_movements(product_id);
create index if not exists idx_movements_created on public.stock_movements(created_at desc);
create index if not exists idx_entry_items_entry on public.stock_entry_items(entry_id);
create index if not exists idx_transfer_items_transfer on public.transfer_items(transfer_id);

