-- ---------- FUNÇÃO AUXILIAR ----------
create or replace function public.get_location_id(p_name text)
returns uuid
language sql
stable
as $$
  select id from public.locations where name = p_name and active = true limit 1;
$$;

-- ---------- ENTRADA DE ITEM NO CONTAINER ----------
create or replace function public.add_entry_item(
  p_entry_id bigint,
  p_product_id uuid,
  p_quantity numeric,
  p_unit text default 'UN'
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_container uuid;
begin
  if p_quantity <= 0 then
    raise exception 'Quantidade deve ser maior que zero';
  end if;

  v_container := public.get_location_id('Container');
  if v_container is null then
    raise exception 'Local Container não encontrado';
  end if;

  insert into public.stock_entry_items(entry_id, product_id, quantity, unit)
  values (p_entry_id, p_product_id, p_quantity, p_unit);

  insert into public.inventory(product_id, location_id, quantity, updated_at)
  values (p_product_id, v_container, p_quantity, now())
  on conflict (product_id, location_id)
  do update set quantity = public.inventory.quantity + excluded.quantity,
                updated_at = now();

  insert into public.stock_movements(
    product_id, location_id, movement_type, quantity,
    reference_type, reference_id, notes
  )
  values (
    p_product_id, v_container, 'ENTRY', p_quantity,
    'stock_entry', p_entry_id::text, 'Entrada de mercadoria no Container'
  );
end;
$$;

-- ---------- TRANSFERÊNCIA CONTAINER -> BARCO ----------
create or replace function public.transfer_container_to_boat(
  p_product_id uuid,
  p_quantity numeric,
  p_notes text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_container uuid;
  v_boat uuid;
  v_available numeric;
  v_transfer_id bigint;
  v_unit text;
begin
  if p_quantity <= 0 then
    raise exception 'Quantidade deve ser maior que zero';
  end if;

  v_container := public.get_location_id('Container');
  v_boat := public.get_location_id('Kattamaram II');

  if v_container is null or v_boat is null then
    raise exception 'Locais de estoque não encontrados';
  end if;

  select quantity into v_available
  from public.inventory
  where product_id = p_product_id
    and location_id = v_container
  for update;

  if coalesce(v_available, 0) < p_quantity then
    raise exception 'Estoque insuficiente no Container. Disponível: %', coalesce(v_available,0);
  end if;

  select unit into v_unit from public.products where id = p_product_id;
  if v_unit is null then
    raise exception 'Produto não encontrado';
  end if;

  insert into public.transfers(from_location_id, to_location_id, notes)
  values (v_container, v_boat, p_notes)
  returning id into v_transfer_id;

  insert into public.transfer_items(transfer_id, product_id, quantity, unit)
  values (v_transfer_id, p_product_id, p_quantity, v_unit);

  update public.inventory
  set quantity = quantity - p_quantity, updated_at = now()
  where product_id = p_product_id and location_id = v_container;

  insert into public.inventory(product_id, location_id, quantity, updated_at)
  values (p_product_id, v_boat, p_quantity, now())
  on conflict (product_id, location_id)
  do update set quantity = public.inventory.quantity + excluded.quantity,
                updated_at = now();

  insert into public.stock_movements(
    product_id, location_id, movement_type, quantity,
    reference_type, reference_id, notes
  )
  values
    (p_product_id, v_container, 'TRANSFER_OUT', -p_quantity,
     'transfer', v_transfer_id::text, p_notes),
    (p_product_id, v_boat, 'TRANSFER_IN', p_quantity,
     'transfer', v_transfer_id::text, p_notes);

  return v_transfer_id;
end;
$$;

-- ---------- TRIGGERS DE updated_at ----------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists inventory_set_updated_at on public.inventory;
create trigger inventory_set_updated_at
before update on public.inventory
for each row execute function public.set_updated_at();

